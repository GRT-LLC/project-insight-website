// Generate src/app/components/Logo.tsx from the design library's normalised marks.
//
// The mark must be INLINE in the DOM for currentColor to inherit — via <img> it
// does not. So the SVG is emitted as JSX rather than imported as a file.
//
// Source of truth: jarvis-travel/design-library brand/logo/normalized/
// Regenerate: node scripts/gen-logo-component.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const LIB = '/Users/brentbailey/code/design-library/brand/logo/normalized';
const OUT = 'src/app/components/Logo.tsx';

/** Pull the inner markup and viewBox out of a normalised SVG. */
function parse(name) {
  const raw = readFileSync(`${LIB}/jarvistravel-${name}-current.svg`, 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(raw)[1];
  const inner = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*data-name="[^"]*"/g, '')
    .replace(/\s*id="[^"]*"/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\n\s*\n/g, '\n')
    .trim();
  return { viewBox, inner };
}

const lockup = parse('lockup');
const wordmark = parse('wordmark');
const icon = parse('icon');

const component = `// GENERATED by scripts/gen-logo-component.mjs — do not hand-edit.
// Source: jarvis-travel/design-library brand/logo/normalized/*-current.svg
//
// The marks use fill="currentColor", so they inherit the surrounding text
// colour. That is the whole mechanism: one file per variant is correct on both
// light and dark grounds with no switching logic, provided the SVG is INLINE.
// Rendering via <img> would break inheritance.
//
// Containment is option B (brand owner, 2026-08-02): the swift stands free in
// clear space, never inside a tile. Colour follows the surface, never the theme
// directly: Moonlight on dark grounds, Neverything on light. Never #fff/#000.

export type LogoVariant = 'lockup' | 'wordmark' | 'icon';

interface LogoProps {
  /** lockup = wordmark + swift (attribution). wordmark = type only. icon = the swift. */
  variant?: LogoVariant;
  className?: string;
  /** Accessible name. Pass null for decorative use alongside visible text. */
  title?: string | null;
}

const VIEWBOX: Record<LogoVariant, string> = {
  lockup: '${lockup.viewBox}',
  wordmark: '${wordmark.viewBox}',
  icon: '${icon.viewBox}',
};

export function Logo({ variant = 'lockup', className, title = 'JarvisTravel' }: LogoProps) {
  const decorative = title === null;
  return (
    <svg
      viewBox={VIEWBOX[variant]}
      fill="currentColor"
      className={className}
      role={decorative ? undefined : 'img'}
      aria-hidden={decorative || undefined}
      aria-label={decorative ? undefined : title}
      xmlns="http://www.w3.org/2000/svg"
    >
      {variant === 'lockup' && (
        <>
${lockup.inner.split('\n').map((l) => '          ' + l.trim()).join('\n')}
        </>
      )}
      {variant === 'wordmark' && (
        <>
${wordmark.inner.split('\n').map((l) => '          ' + l.trim()).join('\n')}
        </>
      )}
      {variant === 'icon' && (
        <>
${icon.inner.split('\n').map((l) => '          ' + l.trim()).join('\n')}
        </>
      )}
    </svg>
  );
}
`;

writeFileSync(OUT, component);
console.log(`wrote ${OUT} (${component.length} bytes)`);
console.log(`viewBoxes: lockup=${lockup.viewBox} wordmark=${wordmark.viewBox} icon=${icon.viewBox}`);
