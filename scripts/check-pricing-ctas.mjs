#!/usr/bin/env node
// Pricing CTA guard: every "Join Now" on the pricing page must link into the
// app carrying a plan, and must name a plan the shared contract knows about.
//
// Why this exists. Until JAR-1184 both CTAs routed to /contact, the waitlist
// form, behind a comment saying they would change when the payment flow was
// live. They now link to app.jarvistravel.com/auth/sign-up?plan=<lookup key>,
// which the app reads to send the visitor straight to checkout for the plan
// they picked.
//
// Two ways that quietly breaks, neither of which the type system sees:
//
//   1. A CTA is reverted to a router <Link to="/contact">. The page still
//      builds, the button still says Join Now, and every visitor lands on the
//      waitlist instead of signup. That is invisible in a diff review of a
//      500-line JSX file and invisible in a screenshot.
//   2. A CTA is given a hand-written href with a plan string in it. The string
//      then drifts from PRICES, which is generated by `npm run sync:prices`
//      from Stripe. A lookup key that no longer exists is dropped silently by
//      the app's allowlist and the visitor is asked to choose all over again.
//
// So this asserts the shape, not the appearance: CTAs go through appJoinUrl(),
// and every literal key handed to it is one PRICES declares.
//
// Shape mirrors the other guards in this directory: same CLI/import split, same
// fail-closed posture, exit 1 on any violation.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = join(import.meta.dirname, '..');
const PAGE = 'src/app/pages/PricingPage.tsx';
const PRICING = 'src/app/data/pricing.ts';

export function checkPricingCtas(root = ROOT) {
  const page = readFileSync(join(root, PAGE), 'utf8');
  const pricing = readFileSync(join(root, PRICING), 'utf8');
  const problems = [];

  // The lookup keys that actually exist, read from the generated block rather
  // than restated here — a guard with its own copy of the answer is a second
  // source of truth that drifts from the first.
  const known = new Set([...pricing.matchAll(/^\s*(jt_[a-z_]+):\s*\{/gm)].map((m) => m[1]));
  if (known.size === 0) {
    problems.push(`${PRICING}: no lookup keys found — the guard cannot verify anything, so it fails rather than passing vacuously`);
  }

  // Every Join Now must sit inside an element whose target calls appJoinUrl.
  //
  // Scanning BACKWARD from each label rather than matching a tag pattern
  // forward: the opening tag and the label are separated by a multi-line
  // className holding backticks, braces and ">" characters, so a forward regex
  // either stops early or swallows the next element. Walking back to the
  // nearest unclosed <a/<Link is the only reading that survives the formatter.
  const labels = [...page.matchAll(/>\s*Join Now\s*</g)];
  if (labels.length === 0) {
    problems.push(`${PAGE}: no "Join Now" CTA found at all — either the page changed shape or this guard is now watching nothing`);
  }

  for (const label of labels) {
    const before = page.slice(0, label.index);
    const open = Math.max(before.lastIndexOf('<a'), before.lastIndexOf('<Link'));
    if (open === -1) {
      problems.push(`${PAGE}: a "Join Now" label has no <a> or <Link> before it`);
      continue;
    }
    const tag = before.slice(open, label.index + 1);
    if (!tag.includes('appJoinUrl')) {
      const target = (tag.match(/(?:href|to)=\{?["']?([^"'}\n]+)/) || [, '(none)'])[1];
      problems.push(`${PAGE}: a "Join Now" CTA targets ${target} instead of appJoinUrl(...) — visitors land there instead of signup`);
    }
  }

  // Any literal key passed to appJoinUrl must be one PRICES declares.
  for (const [, key] of page.matchAll(/appJoinUrl\(\s*'([^']+)'\s*\)/g)) {
    if (!known.has(key)) {
      problems.push(`${PAGE}: appJoinUrl('${key}') names a lookup key PRICES does not declare — known: ${[...known].join(', ')}`);
    }
  }

  return problems;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const problems = checkPricingCtas();
  for (const p of problems) console.error(`  ${p}`);
  console.log(problems.length ? `\n${problems.length} problem(s)` : 'pricing CTAs OK');
  process.exit(problems.length ? 1 : 0);
}
